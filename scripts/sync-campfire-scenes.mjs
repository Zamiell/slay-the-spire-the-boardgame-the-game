// Writes src/game/campfire-scenes.ts: the parties that have a campfire scene, read from
// public/assets/noncombat/campfire/<party>_firecamp.webp. The client picks a party's scene
// from this list (campfireScenePath), so a party without a scene falls back to a listed one
// instead of requesting a file that is not there.
//
//   node scripts/sync-campfire-scenes.mjs          # rewrite the module
//   node scripts/sync-campfire-scenes.mjs --check  # fail if it is stale
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sceneRoot = join(repoRoot, 'public/assets/noncombat/campfire')
const target = join(repoRoot, 'src/game/campfire-scenes.ts')
const suffix = '_firecamp.webp'

/** Party names (`ironclad_silent`), sorted; the empty camp is the fallback, not a party. */
export function campfireScenes() {
  return existsSync(sceneRoot)
    ? readdirSync(sceneRoot)
      .filter((file) => file.endsWith(suffix) && file !== `empty${suffix}`)
      .map((file) => file.slice(0, -suffix.length)).sort()
    : []
}

const render = (scenes) => `// Generated by scripts/sync-campfire-scenes.mjs from public/assets/noncombat/campfire. Do not edit.
// Each entry is a party named by its visual ids in VISUAL_IDS order: \`<party>_firecamp.webp\`.
export const CAMPFIRE_SCENES: readonly string[] = ${JSON.stringify(scenes, null, 2)}
`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render(campfireScenes())
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
      console.error('src/game/campfire-scenes.ts is stale; run node scripts/sync-campfire-scenes.mjs')
      process.exit(1)
    }
  } else writeFileSync(target, next)
}
