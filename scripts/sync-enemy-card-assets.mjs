// Official printed references, separate from the generated battlefield artwork.
// Requires Python Pillow. Source sheets stay in ignored tmp/; only small WebPs
// and the generated runtime index are shipped.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { enemyCardSources } from './lib/enemy-card-sources.mjs'
import { ENEMIES } from '../src/game/enemies.ts'

const root = resolve(import.meta.dirname, '..')
const sheets = JSON.parse(readFileSync(resolve(root, 'data/enemy-card-sheets.json'), 'utf8'))
const cache = resolve(root, 'tmp/enemy-card-sheets')
const output = resolve(root, 'public/assets/enemy-cards')
mkdirSync(cache, { recursive: true })
mkdirSync(output, { recursive: true })
for (const id of Object.keys(ENEMIES)) {
  if (!enemyCardSources.some(card => card.id === id && card.minAscension === 0)) throw new Error(`Missing enemy card: ${id}`)
}
const sources = [...new Set(enemyCardSources.map(card => card.source))]
for (const source of sources) {
  const path = resolve(cache, `${source}.png`)
  if (existsSync(path)) continue
  const response = await fetch(sheets[source].url)
  if (!response.ok) throw new Error(`Enemy sheet ${source}: HTTP ${response.status}`)
  writeFileSync(path, Buffer.from(await response.arrayBuffer()))
}
const result = spawnSync('python3', ['-c', `
import json, sys
from pathlib import Path
from PIL import Image
data = json.load(sys.stdin)
images, sizes, index = {}, {}, {}
for card in data['cards']:
    source = card['source']
    if source not in images:
        images[source] = Image.open(Path(data['cache']) / (source + '.png')).convert('RGB')
    image = images[source]
    sheet = data['sheets'][source]
    cols, rows = sheet['columns'], sheet['rows']
    cell = card['index']
    assert 0 <= cell < cols * rows, card
    key = source + '-' + str(cell)
    if key not in sizes:
        x, y = cell % cols, cell // cols
        crop = image.crop((round(x * image.width / cols), round(y * image.height / rows),
                           round((x + 1) * image.width / cols), round((y + 1) * image.height / rows)))
        crop.thumbnail((896, 640), Image.Resampling.LANCZOS)
        crop.save(Path(data['output']) / (key + '.webp'), quality=85, method=6)
        sizes[key] = crop.size
    width, height = sizes[key]
    index.setdefault(card['id'], []).append({'minAscension': card['minAscension'],
        'file': key, 'width': width, 'height': height})
for variants in index.values():
    variants.sort(key=lambda card: card['minAscension'])
print(json.dumps(index, indent=2))
`], {
  input: JSON.stringify({ cards: enemyCardSources, sheets, cache, output }),
  encoding: 'utf8',
  maxBuffer: 8 * 1024 * 1024,
})
if (result.error) throw result.error
if (result.status !== 0) throw new Error(result.stderr)
writeFileSync(resolve(root, 'src/game/enemy-card-images.ts'),
  '// Generated by scripts/sync-enemy-card-assets.mjs. Do not edit by hand.\n' +
  'export type EnemyCardImage = { minAscension: number; file: string; width: number; height: number }\n' +
  `export const ENEMY_CARD_IMAGES: Record<string, readonly EnemyCardImage[]> = ${result.stdout.trim()}\n`)
console.log(`Exported printed references for ${Object.keys(ENEMIES).length} enemies.`)
