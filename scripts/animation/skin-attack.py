"""Generate the staged attack animation of every skin from scripts/animation/skins/<skin>.json.

  python3 scripts/animation/skin-attack.py                  write the CSS and the TypeScript table
  python3 scripts/animation/skin-attack.py --check          fail when either is stale (verify-assets runs this)
  python3 scripts/animation/skin-attack.py --measure SKIN   print the pose shifts and contact reach of its baked drawings
                                                            (--write stores them in the config; --check fails when the stored
                                                            poseShift/contactReach differ, read-only; verify-assets runs it)
  python3 scripts/animation/skin-attack.py --bake-rest SKIN idle loop, reduced-motion hero and list icon from <skin>-ready.webp
  python3 scripts/animation/skin-attack.py --fixture DIR    synthetic test skins (scripts/animation/test-skins/*.json),
                                                            drawn as solid shapes, for the browser verifier; nothing is registered

The config format is documented in docs/skins/attack-animation.md. The generated files hold every skin:
src/ui/styles/staged-attacks.css (clock, travel and pose opacity) and src/ui/combat-screen/staged-attacks.ts
(poses, cues, hits and sound volumes). One generic implementation reads them by visual id.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

from skin_geometry import SOLE_BAND, bake_rest_art, dump_config, hold_problems, rear_foot_centre, solid_box

ROOT = Path(__file__).resolve().parents[2]
SKINS = ROOT / 'scripts/animation/skins'
TEST_SKINS = ROOT / 'scripts/animation/test-skins'
CSS = ROOT / 'src/ui/styles/staged-attacks.css'
TS = ROOT / 'src/ui/combat-screen/staged-attacks.ts'
CHARACTERS = ROOT / 'public/assets/combat/characters'
HIT_STYLES = ('strike', 'slam')
MAX_KEYS = 24
# `--measure SKIN --check` accepts re-measurement noise of this size against the stored poseShift (canvas px) and contactReach.
SHIFT_TOLERANCE_PX = 2
REACH_TOLERANCE = 0.005
HEADER = 'generated by scripts/animation/skin-attack.py from scripts/animation/skins/*.json; do not edit.'


def load(directory):
    configs = {}
    for path in sorted(directory.glob('*.json')):
        config = json.loads(path.read_text())
        assert config['skin'] == path.stem, f'{path.name}: "skin" must be {path.stem}'
        configs[config['skin']] = config
    return configs


def file_name(pose):
    """The idle key is the rest drawing, saved as <skin>-ready.webp."""
    return 'ready' if pose == 'idle' else pose


def poses_of(config):
    return list(dict.fromkeys(pose for _, pose in config['keys']))


def onset(config, at):
    """A hit or cue time: milliseconds, or the first moment a named pose is shown."""
    if isinstance(at, (int, float)):
        return at
    return next(time for time, pose in config['keys'] if pose == at)


def validate(config):
    skin, duration, keys = config['skin'], config['durationMs'], config['keys']
    times = [time for time, _ in keys]
    assert times[0] == 0 and times == sorted(set(times)) and times[-1] < duration, f'{skin}: keys must ascend from 0 inside the clock'
    assert keys[0][1] == keys[-1][1] == 'idle', f'{skin}: the clock starts and ends on the idle drawing'
    assert len(keys) <= MAX_KEYS, f'{skin}: more than {MAX_KEYS} keys'
    assert min(b - a for a, b in zip(times, times[1:] + [duration])) >= 20, f'{skin}: a key shorter than 20ms'
    assert not hold_problems(config), '; '.join(hold_problems(config))
    poses = poses_of(config)
    (out_start, out_end), (back_start, back_end) = config['travel']['out'], config['travel']['back']
    assert 0 <= out_start < out_end <= back_start < back_end <= duration, f'{skin}: travel must go out, then back, inside the clock'
    validate_path(config)
    assert set(config.get('poseShift', {})) <= set(poses), f'{skin}: poseShift names an unknown pose'
    assert config['contactPoses'] and set(config['contactPoses']) <= set(poses), f'{skin}: contactPoses must be poses'
    assert config['hits'], f'{skin}: at least one hit'
    assert abs(sum(hit['weight'] for hit in config['hits']) - 1) < 1e-9, f'{skin}: hit weights must add up to 1'
    for hit in config['hits']:
        assert hit['style'] in HIT_STYLES, f'{skin}: hit style must be one of {HIT_STYLES}'
        assert hit['sound'] in config['sounds'], f'{skin}: hit sound {hit["sound"]} has no volume in "sounds"'
        assert 'pin' not in hit or hit['style'] == 'strike' and set(hit['pin']) == {'dx', 'up', 'pivot'} and len(hit['pin']['pivot']) == 2, f'{skin}: a hit pin is {{dx, up, pivot: [x, y]}} on a strike'
    for cue in config.get('cues', []):
        assert cue['sound'] in config['sounds'], f'{skin}: cue sound {cue["sound"]} has no volume in "sounds"'
    for step in [*config['hits'], *config.get('cues', [])]:
        at = step['at']
        assert isinstance(at, (int, float)) and 0 <= at < duration or at in poses, f'{skin}: "at" {at!r} is neither a pose nor a time'
    hit_times = [onset(config, hit['at']) for hit in config['hits']]
    assert hit_times == sorted(hit_times), f'{skin}: hits must be listed in time order'
    assert 'contactReach' in config, f'{skin}: run --measure {skin} --write once its drawings are baked'


def validate_path(config):
    """An optional travel.path = {"out": [[ms, f]...], "back": [[ms, f]...]} shapes the dash: f is the fraction of the way to the target."""
    path = config['travel'].get('path')
    if path is None:
        return
    skin = config['skin']
    (out_start, out_end), (back_start, back_end) = config['travel']['out'], config['travel']['back']
    for leg, (start, end), first, last in (('out', (out_start, out_end), 0, 1), ('back', (back_start, back_end), 1, 0)):
        points = path[leg]
        times, fractions = [time for time, _ in points], [fraction for _, fraction in points]
        assert times[0] == start and times[-1] == end and times == sorted(set(times)), f'{skin}: travel.path.{leg} must ascend from {start} to {end}'
        assert fractions[0] == first and fractions[-1] == last, f'{skin}: travel.path.{leg} must run {first} -> {last}'
        assert fractions == sorted(fractions, reverse=first == 1), f'{skin}: travel.path.{leg} must be monotonic (the actor never backs up mid-leg)'


def travel_css(config):
    """The travel keyframes: one ease-in-out dash by default, or the straight segments of travel.path (each key of the clock sets its own speed)."""
    skin, travel = config['skin'], config['travel']
    (out_start, out_end), (back_start, back_end) = travel['out'], travel['back']
    if 'path' not in travel:
        return [f'@keyframes {skin}-travel {{',
                f'  0%, {pct(config, out_start)}, {pct(config, back_end)}, 100% {{ transform: translate(0); }}',
                f'  {pct(config, out_end)}, {pct(config, back_start)} {{ transform: translate(var(--attack-x), var(--attack-y)); }}',
                '}']
    at = lambda fraction: 'translate(0)' if fraction == 0 else (
        'translate(var(--attack-x), var(--attack-y))' if fraction == 1 else
        f'translate(calc(var(--attack-x) * {fraction}), calc(var(--attack-y) * {fraction}))')
    stops = [(0, 0), *travel['path']['out'], *travel['path']['back'], (config['durationMs'], 0)]
    return [f'@keyframes {skin}-travel {{', *(f'  {pct(config, ms)} {{ transform: {at(fraction)}; }}' for ms, fraction in stops), '}']


def pct(config, ms):
    return f'{ms * 100 / config["durationMs"]:.4f}'.rstrip('0').rstrip('.') + '%'


def visibility(config, name):
    """Opacity keyframes showing a drawing during each of its key intervals."""
    keys, duration = config['keys'], config['durationMs']
    times = [time for time, _ in keys] + [duration]
    shown, hidden = [], []
    for index, (start, pose) in enumerate(keys):
        if pose != name:
            continue
        end = times[index + 1]
        shown += [pct(config, start), pct(config, end - .01) if end < duration else '100%']
        if start > 0:
            hidden.append(pct(config, start - .01))
        if end < duration:
            hidden.append(pct(config, end))
    if keys[0][1] != name:
        hidden.insert(0, '0%')
    if keys[-1][1] != name:
        hidden.append('100%')
    rules = [f'  {", ".join(hidden)} {{ opacity: 0; }}'] if hidden else []
    return [f'@keyframes {config["skin"]}-{file_name(name)} {{', *rules, f'  {", ".join(shown)} {{ opacity: 1; }}', '}']


def skin_css(config):
    skin, duration = config['skin'], config['durationMs']
    # A contained square canvas maps one canvas pixel to min(width, height) * displayScale / canvas.
    factor = round(100 * config['displayScale'] / config['canvas'], 6)
    shift = config.get('poseShift', {})
    easing = 'linear' if 'path' in config['travel'] else 'ease-in-out'
    lines = [f'/* {skin} */',
             f'.character-attack--{skin} {{',
             '  container-type: size;',
             '  will-change: transform;',
             f'  animation: {skin}-travel {duration}ms {easing} both;',
             '}',
             *travel_css(config),
             f'.character-attack--{skin} .character-attack__pose {{',
             f'  translate: calc(var(--pose-x, 0) * min(1cqw, 1cqh) * {factor}) 0;',
             '}']
    for pose in poses_of(config):
        name = file_name(pose)
        var = f' --pose-x: {shift[pose]};' if pose in shift else ''
        lines.append(f'.character-attack__pose--{skin}-{name} {{ animation: {skin}-{name} {duration}ms linear both;{var} }}')
    for pose in poses_of(config):
        lines += visibility(config, pose)
    lines += [f'/* Out at the target the {skin} skin draws in front of every enemy, bosses included: its seat rises above the',
              '   enemies in its row and its row above the bosses. Targeting flattens the rows, leaving the seat on top. */',
              f'.board:not(:has(.enemy--targeted, .row__enemies--targetable)) > .row:has(.character-attack--{skin}),',
              f'.row__seat:has(.character-attack--{skin}) {{ z-index: 101; }}',
              '/* WebKit rasterizes a scaled animated WebP at its filtered surface\'s small layout size: keep the overscanned idle sharp. */',
              f'.board .seat__interactive[data-character=\'{skin}\'] .seat:not(.seat--dead),',
              f'.board .seat__interactive[data-character=\'{skin}\'] .seat:not(.seat--dead) .seat__portrait > img {{',
              '  filter: none;',
              '}']
    return '\n'.join(lines)


def css_text(configs):
    return '\n'.join([f'/* {HEADER} */', *(skin_css(config) for config in configs.values())]) + '\n'


def literal(value):
    return json.dumps(value).replace('"', "'")


def spec_dict(config):
    return {
        'durationMs': config['durationMs'],
        'displayScale': config['displayScale'],
        'contactReach': config['contactReach'],
        'poses': [file_name(pose) for pose in poses_of(config)],
        'cues': [{'ms': onset(config, cue['at']), 'sound': cue['sound']} for cue in config.get('cues', [])],
        'hits': [{'ms': onset(config, hit['at']), 'weight': hit['weight'], 'style': hit['style'],
                  'angle': hit.get('angle', 0), 'vfx': hit['vfx'], 'sound': hit['sound'],
                  **({'pin': hit['pin']} if 'pin' in hit else {})} for hit in config['hits']],
    }


def spec_ts(config):
    spec = spec_dict(config)
    cues = ', '.join(f"{{ ms: {cue['ms']}, sound: {literal(cue['sound'])} }}" for cue in spec['cues'])
    hits = '\n'.join(
        f"      {{ ms: {hit['ms']}, weight: {hit['weight']}, style: {literal(hit['style'])}, "
        f"angle: {hit['angle']}, vfx: {literal(hit['vfx'])}, sound: {literal(hit['sound'])}"
        f"{', pin: ' + literal(hit['pin']) if 'pin' in hit else ''} }},"
        for hit in spec['hits'])
    return '\n'.join([
        f"  {config['skin']}: {{",
        f"    durationMs: {spec['durationMs']},",
        f"    displayScale: {spec['displayScale']},",
        f"    contactReach: {spec['contactReach']},",
        f"    poses: [{', '.join(literal(pose) for pose in spec['poses'])}],",
        f"    cues: [{cues}],",
        '    hits: [', hits, '    ],',
        '  },'])


def ts_text(configs):
    volumes = {sound: volume for config in configs.values() for sound, volume in config['sounds'].items()}
    return '\n'.join([
        f'// {HEADER}',
        '',
        '/** A hit lands `ms` into the attack and takes `weight` of the damage (the weights of an attack add up to 1). */',
        'export interface StagedHit {',
        '  readonly ms: number',
        '  readonly weight: number',
        '  /** A rotated flash on the target\'s body (`strike`) or a ground shock under it (`slam`). */',
        "  readonly style: 'strike' | 'slam'",
        '  readonly angle: number',
        '  readonly vfx: string',
        '  /** Pins a `strike` flash to the weapon tip: its `pivot` (percent of the flash) sits `dx` actor edges right of the target\'s body and `up` above the ground line under it. */',
        '  readonly pin?: { readonly dx: number; readonly up: number; readonly pivot: readonly [number, number] }',
        '  readonly sound: string',
        '}',
        '',
        'export interface StagedAttackSpec {',
        '  readonly durationMs: number',
        '  /** The drawings are baked with this much transparent overscan. */',
        '  readonly displayScale: number',
        '  /** The weapon-tip line, in contained canvas edges right of the actor centre. */',
        '  readonly contactReach: number',
        '  /** Every drawing, by its runtime file name (`<skin>-<pose>.webp`). */',
        '  readonly poses: readonly string[]',
        '  readonly cues: readonly { readonly ms: number; readonly sound: string }[]',
        '  readonly hits: readonly StagedHit[]',
        '}',
        '',
        'export const STAGED_ATTACKS = {',
        *(spec_ts(config) for config in configs.values()),
        '} as const satisfies Record<string, StagedAttackSpec>',
        '',
        'export const STAGED_SOUND_VOLUMES = {',
        *(f'  {literal(sound)}: {volume},' for sound, volume in volumes.items()),
        '} as const',
        '',
    ])


def baked(config, root=CHARACTERS):
    return {pose: Image.open(root / f'animated/{config["skin"]}-{file_name(pose)}.webp').convert('RGBA')
            for pose in poses_of(config)}


def measure(config, images):
    """Planting shifts (rear sole of every drawing onto the idle rear sole) and the weapon-tip reach."""
    size = config['canvas']
    options = config.get('measure', {})
    idle_rows, pose_rows = options.get('idleRows', SOLE_BAND), options.get('poseRows', SOLE_BAND)
    idle_rear = rear_foot_centre(images['idle'], idle_rows)
    shifts = {pose: round(idle_rear - rear_foot_centre(image, pose_rows)) for pose, image in images.items()
              if pose != 'idle' and pose not in options.get('unplanted', [])}
    tips = [solid_box(images[pose])[2] + shifts.get(pose, 0) for pose in config['contactPoses']]
    reach = round((sum(tips) / len(tips) - size / 2) * config['displayScale'] / size, 4)
    return {pose: shift for pose, shift in shifts.items() if shift}, reach, max(tips) - min(tips)


def stale_measurements(config, shifts, reach):
    """Where the config's stored poseShift/contactReach differ from a fresh measurement beyond the re-measurement noise."""
    stored = config.get('poseShift', {})
    problems = [f'poseShift {pose} stored {stored.get(pose, 0)}, measured {shifts.get(pose, 0)}'
                for pose in sorted(stored.keys() | shifts.keys()) if abs(stored.get(pose, 0) - shifts.get(pose, 0)) > SHIFT_TOLERANCE_PX]
    if abs(config['contactReach'] - reach) > REACH_TOLERANCE:
        problems.append(f'contactReach stored {config["contactReach"]}, measured {reach}')
    return problems


def synthetic_poses(config):
    """Solid-colour stand-ins: a body on two feet, an arm reaching one fixed length from the rear foot in the contact poses, a raised fist in the windup."""
    size, ground = config['canvas'], config['ground']
    palette = ['#e8584f', '#f2a33c', '#e8d44d', '#6cc24a', '#3fb8af', '#3b7dd8', '#7a5fd0', '#c14fb0']
    poses = poses_of(config)
    images = {}
    for index, pose in enumerate(poses):
        image = Image.new('RGBA', (size, size))
        draw = ImageDraw.Draw(image)
        colour = palette[index % len(palette)]
        # Every drawing stands a little off the others, like real art, so planting has work to do.
        dx = (index * 7) % 24 - 12 if pose != 'idle' else 0
        left = size // 2 - 16 + dx
        draw.rectangle((left, ground - 76, left + 32, ground - 10), fill=colour)
        draw.rectangle((left, ground - 10, left + 12, ground), fill=colour)
        draw.rectangle((left + 20, ground - 10, left + 32, ground), fill=colour)
        if pose in config['contactPoses']:
            draw.rectangle((left + 32, ground - 26, left + 64, ground - 20), fill='#ffffff')
        elif 'windup' in pose or 'anticipation' in pose:
            draw.rectangle((left + 8, ground - 100, left + 24, ground - 76), fill=colour)
        images[pose] = image
    return images


def write_fixture(out):
    configs = load(TEST_SKINS)
    for config in configs.values():
        skin = config['skin']
        images = synthetic_poses(config)
        shifts, reach, spread = measure({**config, 'contactReach': 0}, images)
        assert spread <= config.get('contactTolerance', 12), f'{skin}: synthetic contact reach differs ({spread})'
        config.update(poseShift=shifts, contactReach=reach)
        validate(config)
        root = out / 'assets/combat/characters'
        for pose, image in images.items():
            (root / 'animated').mkdir(parents=True, exist_ok=True)
            image.save(root / f'animated/{skin}-{file_name(pose)}.webp', lossless=True)
        bake_rest_art(images['idle'], config, root, out)
        for vfx in {hit['vfx'] for hit in config['hits']}:
            target = out / f'assets/combat/vfx/actions/{skin}/{vfx}.webp'
            target.parent.mkdir(parents=True, exist_ok=True)
            flash = Image.new('RGBA', (64, 64))
            ImageDraw.Draw(flash).ellipse((4, 4, 60, 60), fill=(255, 240, 120, 230))
            flash.save(target, lossless=True)
    (out / 'staged-attacks.css').write_text(css_text(configs))
    (out / 'staged-attacks.json').write_text(json.dumps({
        'configs': configs,
        'table': {skin: spec_dict(config) for skin, config in configs.items()},
        'sounds': {sound: volume for config in configs.values() for sound, volume in config['sounds'].items()}}, indent=1))
    print(f'fixture skins {", ".join(configs)} written to {out}')


def main(argv):
    configs = load(SKINS)
    if '--fixture' in argv:
        write_fixture(Path(argv[argv.index('--fixture') + 1]).resolve())
        return
    if '--measure' in argv or '--bake-rest' in argv:
        flag = '--measure' if '--measure' in argv else '--bake-rest'
        config = configs[argv[argv.index(flag) + 1]]
        images = baked({**config, 'contactReach': 0})
        if flag == '--bake-rest':
            bake_rest_art(images['idle'], config, CHARACTERS, ROOT)
            return
        shifts, reach, spread = measure(config, images)
        print(json.dumps({'poseShift': shifts, 'contactReach': reach, 'contactSpreadPx': spread}, indent=2))
        assert spread <= config.get('contactTolerance', 12), f'{config["skin"]}: contact poses reach {spread}px apart; redraw them to one reach'
        if '--check' in argv:
            problems = stale_measurements(config, shifts, reach)
            assert not problems, f'{config["skin"]}: {"; ".join(problems)}; run --measure {config["skin"]} --write'
            print(f'PASS: {config["skin"]} poseShift and contactReach match its baked drawings')
        if '--write' in argv:
            (SKINS / f'{config["skin"]}.json').write_text(dump_config({**config, 'poseShift': shifts, 'contactReach': reach}))
        return
    for config in configs.values():
        validate(config)
    css, ts = css_text(configs), ts_text(configs)
    if '--check' in argv:
        assert (CSS.read_text(), TS.read_text()) == (css, ts), 'staged attack CSS or table is stale; run scripts/animation/skin-attack.py'
        print(f'PASS: staged attack CSS and table match {", ".join(configs)}')
        return
    CSS.write_text(css)
    TS.write_text(ts)


if __name__ == '__main__':
    main(sys.argv[1:])
